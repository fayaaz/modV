Scene makeScene(float id) {
    Scene s;
    s.sd    = mod(id * 7.31, 97.0) + h11(id) * 13.0;
    s.lay   = gLay >= 0 ? gLay : pickI(6, h21(vec2(id, 1.1)));
    s.pal   = pickI(12, h21(vec2(id, 2.2)));
    s.sty   = pickI(5, h21(vec2(id, 3.3)));
    s.hero  = pickI(7, h21(vec2(id, 4.4)));
    s.bg    = sel(pickI(6, h21(vec2(id, 5.5))), 0, 1, 2, 3, 4, 6, 6);
    s.head  = G_HEAD  + pickI(N_HEAD,  h21(vec2(id, 6.6)));
    s.head2 = G_HEAD2 + pickI(N_HEAD2, h21(vec2(id, 7.7)));
    s.tag   = G_TAG   + pickI(N_TAG,   h21(vec2(id, 8.8)));
    int i0  = pickI(N_INFO, h21(vec2(id, 9.9)));
    s.i0    = G_INFO + i0;
    s.i1    = G_INFO + imod(i0 + 1 + pickI(N_INFO - 1, h21(vec2(id, 10.1))), N_INFO);
    s.dj    = pickI(N_DJ, h21(vec2(id, 11.1)));
    s.quad  = pickI(N_QUAD, h21(vec2(id, 12.1)));
    s.date  = G_DATE  + pickI(N_DATE,  h21(vec2(id, 13.1)));
    s.place = G_PLACE + pickI(N_PLACE, h21(vec2(id, 14.1)));
    s.hour  = G_HOUR  + pickI(N_HOUR,  h21(vec2(id, 15.1)));
    s.yr    = G_YEAR  + pickI(N_YEAR,  h21(vec2(id, 16.1)));
    s.marq  = G_MARQ  + pickI(N_MARQ,  h21(vec2(id, 17.1)));
    s.echo  = h21(vec2(id, 18.1)) < 0.5;
    s.inv   = h21(vec2(id, 19.1)) < 0.2;
    float hb = h21(vec2(id, 20.1)), hc = h21(vec2(id, 21.1)), hd = h21(vec2(id, 22.1));
    if (s.lay == 1) {
        s.bg   = sel(pickI(4, hb), 5, 3, 2, 6, 0, 0, 0);
        s.hero = sel(pickI(5, hc), 3, 2, 0, 6, 3, 0, 0);
        s.pal  = sel(pickI(7, hd), 3, 2, 0, 4, 6, 9, 11);
        s.echo = true; s.inv = false;
    }
    if (s.lay == 2) { s.bg = 1; s.pal = sel(pickI(5, hd), 5, 11, 7, 10, 2, 0, 0); s.inv = false; }
    if (s.lay == 3) { s.bg = 5; s.pal = sel(pickI(6, hd), 8, 1, 10, 5, 7, 4, 0); s.inv = false; }
    if (s.lay == 4) {
        s.bg   = sel(pickI(4, hb), 2, 2, 6, 0, 0, 0, 0);
        s.hero = sel(pickI(5, hc), 1, 4, 3, 0, 1, 0, 0);
        s.pal  = sel(pickI(6, hd), 7, 10, 5, 1, 8, 11, 0);
        s.inv  = false;
    }
    if (s.lay == 5) s.pal = sel(pickI(7, hd), 1, 0, 2, 3, 4, 8, 9);
    return s;
}

