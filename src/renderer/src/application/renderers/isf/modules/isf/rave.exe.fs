#define SOLID vec3(0.0, 0.0, 0.16)

// glyph index at offset o (0..15) of a text-store leaf (4 floats x 4 six-bit chars)
float charIn(vec4 lf, float o) {
    float comp = floor(o / 4.0);
    float sub = o - comp * 4.0;
    float v = dot(lf, vec4(equal(vec4(comp), vec4(0.0, 1.0, 2.0, 3.0))));
    float inv = sub < 0.5 ? 1.0 : (sub < 1.5 ? 0.015625 : (sub < 2.5 ? 0.000244140625 : 0.000003814697265625));
    return mod(floor(v * inv), 64.0);
}
// glyph indices of store characters idx and idx+1 (leaves overlap by one, so one lookup)
vec2 charPair(float idx) {
    float k = floor((idx + 0.5) / 15.0);
    float o = idx - 15.0 * k;
    vec4 lf = txtLeaf(k);
    return vec2(charIn(lf, o), charIn(lf, o + 1.0));
}

// signed distance to a line of text
//  org = bottom-left of first cell, cs = cell size (6x5 font pixels incl. spacing)
//  start/L = the word's characters, scr = scroll in characters, rep = endless repeat
//  sh  = (corner rounding, extra bold, horizontal stem bold) in font pixels
float sdText(vec2 p, vec2 org, vec2 cs, float start, float L, float scr, bool rep, vec3 sh) {
    vec2 q = (p - org) / cs;
    if (q.y < -0.35 || q.y > 1.35) return 1.0;
    if (rep) q.x += mod(scr, L);
    else if (q.x < -0.35 || q.x > L + 0.2) return 1.0;
    vec2 u = cs / vec2(6.0, 5.0);
    float mu = min(u.x, u.y);
    vec2 hb = 0.5 * u + vec2(sh.z * u.x, 0.0);
    float rr = sh.x * mu;
    vec2 g = q * vec2(6.0, 5.0);
    vec2 gi = floor(g - 0.5);                      // nearest 2x2 font pixels: gi .. gi+1
    // (all styles stay within half a font pixel of the glyph, so 2x2 is exact enough)
    // the 2x2 block touches at most two characters (c0, c0+1): fetch both once.
    // Repeating words are stored with their first char appended, so c0+1 never wraps.
    float c0 = floor((gi.x + 0.5) / 6.0);
    float b = rep ? c0 - L * floor((c0 + 0.5) / L) : c0;
    bool shift = b < -0.5;                         // left of a plain word: only c0+1 can show
    vec2 cp = charPair(start + b + (shift ? 1.0 : 0.0));
    bool v0 = !shift && (rep || b < L - 0.5);
    bool v1 = rep || (b > -1.5 && b < L - 1.5);
    vec2 g0 = vec2(0.0), g1 = vec2(0.0);
    for (int q = 0; q < 2; q++) {                  // loop keeps one copy of the font table
        if (q == 0 ? !v0 : !v1) continue;
        vec2 gb = fontBits(q == 0 ? cp.x : (shift ? cp.x : cp.y));
        if (q == 0) g0 = gb; else g1 = gb;
    }
    float d = 1.0;
    for (int j = 0; j < 2; j++) {
        float cy = gi.y + float(j);
        if (cy < 0.0 || cy > 4.0) continue;
        for (int i = 0; i < 2; i++) {
            float cx = gi.x + float(i);
            float ci = floor((cx + 0.5) / 6.0);
            float cc = cx - ci * 6.0;
            if (cc > 4.5) continue;
            vec2 gl = ci < c0 + 0.5 ? g0 : g1;
            float bi = cy * 5.0 + 4.0 - cc;                // bit index 0..24
            float half_ = bi < 9.5 ? gl.y : gl.x;
            float e = bi < 9.5 ? bi : bi - 10.0;
            if (mod(floor((half_ + 0.5) / exp2(e)), 2.0) < 0.5) continue;
            vec2 lp = (g - vec2(cx, cy) - 0.5) * u;
            d = min(d, sh.x > 0.49 ? length(lp) - 0.5 * mu : sdRBox(lp, hb, rr));
        }
    }
    return d - sh.y * mu - 0.6 * gPX;
}
// headline styles: 0 block, 1 dot-matrix, 2 outline, 3 bubble, 4 drop shadow
vec3 styShape(int sty) {
    if (sty == 1) return vec3(0.5, -0.06, 0.0);
    if (sty == 2) return vec3(0.0, 0.25, 0.0);
    if (sty == 3) return vec3(0.42, 0.28, 0.12);
    return SOLID;
}
float textMask(float d, int sty, vec2 cs) {
    if (sty == 2) return strokeD(d, 0.09 * min(cs.x / 6.0, cs.y / 5.0) + 0.3 * gPX);
    return fillD(d);
}

// Each layout describes its type as text items. Text lines never overlap, so
// every pixel picks the one item that can cover it (textSlot) and a single
// shared renderer sizes and draws it - the word tables and glyph loop exist
// once in the compiled shader, which keeps WebGL / ISF compile times short.
//   sz = (bw, cxm, cym, st):
//   cell width  = min(bw / (len - 1/6), cxm),  cell height = min(cym, width * st)
//   origin      = anc - (text width, cell height) * aln
// The item lands in the t* globals; scroll / repeat / wobble / alpha are the gT* globals.
vec2  tP, tAnc, tAln;
vec4  tSz;
int   tW, tSty;
vec3  tCol;
void tItem(vec2 p, vec2 anc, vec2 aln, int w, vec4 sz, int sty, vec3 col) {
    tP = p; tAnc = anc; tAln = aln; tSz = sz; tW = w; tSty = sty; tCol = col;
}

// ====================================================================
//  BACKGROUNDS  ->  (ink coverage, ink->accent mix)
// ====================================================================
float ripField(vec2 c, float sd) {
    return fbm(c * 1.5 + vec2(sd * 3.7, gT * 0.1)) * 2.2 + length(c * vec2(1.0, 0.8)) * 1.4 + 0.12 * gKick;
}
float halftone(vec2 p, float v, float cell) {
    vec2 f = fract(rot(0.785398) * p / cell) - 0.5;
    return fillD((length(f) - sqrt(clamp(v, 0.0, 1.0)) * 0.6) * cell);
}

vec2 background(vec2 c, int type, float sd) {
    float r = length(c);
    if (type == 0) {                               // warped checkerboard
        if (h11(sd * 3.1) < 0.5) {
            vec2 q = rot(2.4 * sin(gT * 0.45 + sd) * exp(-r * 2.2) + gT * 0.12) * c;
            float sc = 7.0 + 2.0 * h11(sd);
            q *= sc;
            q += 0.4 * vec2(sin(q.y * 0.6 + gT * 1.3), cos(q.x * 0.6 - gT * 1.1));
            float fw = PI * sc * gPX * 1.6;
            return vec2(0.5 + 0.5 * clamp(sin(q.x * PI) / fw, -1.0, 1.0) * clamp(sin(q.y * PI) / fw, -1.0, 1.0), 0.0);
        }
        float a = atan(c.y, c.x);                  // log-polar checker tunnel
        float u = a / TAU * 16.0 + gT * 0.2 + 0.35 * sin(r * 9.0 - gT * 2.0);
        float z = log(r + 1e-4) * 5.0 - gT * 1.5;
        float fu = PI * (16.0 / TAU / max(r, 1e-3) + 3.2) * gPX * 1.3;
        float fz = PI * 5.0 / max(r, 1e-3) * gPX * 1.3;
        return vec2(0.5 + 0.5 * clamp(sin(u * PI) / fu, -1.0, 1.0) * clamp(sin(z * PI) / fz, -1.0, 1.0), 0.0);
    }
    if (type == 1) {                               // wireframe box tunnel
        vec2 q = rot(0.2 * sin(gT * 0.35 + sd)) * c + 0.03 * vec2(sin(gT * 0.7), cos(gT * 0.5));
        float ax = abs(q.x), ay = abs(q.y), m = max(max(ax, ay), 1e-3);
        float zz = 0.3 / m + gT * 1.8;
        float dz = abs(fract(zz + 0.5) - 0.5) * m * m / 0.3;
        float u = (ax > ay ? q.y : q.x) / m;
        float du = abs(fract(u * 3.0 + 0.5) - 0.5) * m / 3.0;
        float w = 0.0012 + 0.01 * m;
        float ln = max(fillD(dz - w), fillD(du - w)) * smoothstep(0.02, 0.12, m);
        return vec2(ln, smoothstep(0.08, 0.45, m));
    }
    if (type == 2) {                               // contour ripples
        float f0 = ripField(c, sd);
        vec2 gr = vec2(ripField(c + vec2(gPX, 0.0), sd) - f0, ripField(c + vec2(0.0, gPX), sd) - f0) / gPX;
        float N = 6.0 + 4.0 * h11(sd * 5.3);
        float v = f0 * N - gT * 0.9;
        float gl = max(length(gr) * N, 1e-3);
        float d = h11(sd * 7.7) < 0.5 ? (abs(fract(v) - 0.5) - 0.25) / gl
                                      : abs(fract(v + 0.5) - 0.5) / gl - 0.0025;
        return vec2(fillD(d), 0.0);
    }
    if (type == 3) {                               // halftone shock rings
        float v = 0.5 + 0.5 * sin(r * 10.0 - gT * 3.0 + fbm(c * 2.5 + sd) * 4.0);
        v = v * (1.0 - smoothstep(0.25, 0.95, r)) + 0.2 * gKick;
        return vec2(halftone(c, v, 0.016), 0.0);
    }
    if (type == 4) {                               // sunburst
        float a = atan(c.y, c.x);
        float N = 18.0 + 2.0 * floor(h11(sd * 2.9) * 6.0);
        float u = a / TAU * N + gT * 0.15 + 0.25 * sin(r * 7.0 - gT * 2.5);
        float d = (abs(fract(u) - 0.5) - 0.25) * TAU * r / N;
        return vec2(fillD(d) * smoothstep(0.0, 0.04, r), 0.0);
    }
    if (type == 6) {                               // op-art moire
        vec2 a = vec2(sin(gT * 0.6), cos(gT * 0.45)) * 0.2;
        vec2 b = vec2(cos(gT * 0.37 + 1.0), sin(gT * 0.52)) * 0.22;
        float k = 30.0;
        float m1 = fillD((abs(fract(length(c - a) * k) - 0.5) - 0.25) / k);
        float m2 = fillD((abs(fract(length(c - b) * k) - 0.5) - 0.25) / k);
        return vec2(m1 + m2 - 2.0 * m1 * m2, 0.0);
    }
    // 5: plain stock with drifting sparkles
    vec2 g = c * 6.0 + vec2(0.0, gT * 0.2);
    vec2 id = floor(g), f = fract(g) - 0.5;
    float h = h21(id + sd);
    if (h > 0.78) {
        vec2 o = (h22(id + sd) - 0.5) * 0.4;
        float s = 0.18 * (0.6 + 0.4 * sin(gT * 4.0 + h * 40.0));
        return vec2(fillD(sdStar(rot(gT * (h - 0.9) * 4.0) * (f - o), s, 4.0, 2.3) / 6.0), 0.0);
    }
    return vec2(0.0);
}

// ====================================================================
//  HERO GRAPHICS  ->  (ink sdf, silhouette sdf)
// ====================================================================
vec3 smileyShape(vec2 p, float R, bool filled) {      // (ink, face, features)
    float face = length(p) - R;
    float bl = 1.0 - smoothstep(0.0, 0.05, abs(fract(gBeat * 0.25 + 0.4) - 0.05));
    vec2 ep = vec2(abs(p.x) - 0.33 * R, p.y - 0.2 * R);
    float eye = sdEll(ep, vec2(0.1, mix(0.19, 0.03, bl)) * R);
    float ta = 1.0 + 0.25 * gKick;
    float mouth = sdArc(vec2(p.x, -p.y), vec2(sin(ta), cos(ta)), 0.58 * R, 0.06 * R);
    float feat = min(eye, mouth);
    float ink = filled ? max(face, -feat) : min(abs(face) - 0.045 * R, feat);
    return vec3(ink, face, feat);
}

vec2 globe(vec2 p, float R, Scene s) {
    float r = length(p);
    float sil = r - R;
    float lw = R * 0.018;
    float ink = abs(sil) - lw * 1.3;
    if (r < R) {
        float z = sqrt(max(R * R - r * r, 0.0)) / R;
        float ay = gT * 0.6 + s.sd, ax = 0.35 + 0.25 * sin(gT * 0.3);
        float lonN = 10.0 + 2.0 * floor(h11(s.sd) * 3.0);
        for (int k = 0; k < 2; k++) {
            vec3 q = vec3(p / R, k == 0 ? z : -z);
            q.yz = rot(ax) * q.yz;
            q.xz = rot(ay) * q.xz;
            float lat = asin(clamp(q.y, -1.0, 1.0));
            float lon = atan(q.x, q.z);
            float dLon = abs(fract(lon / TAU * lonN + 0.5) - 0.5) * TAU / lonN * cos(lat) * R;
            float dLat = abs(fract(lat / PI * 8.0 + 0.5) - 0.5) * PI / 8.0 * R;
            ink = min(ink, min(dLon, dLat) - (k == 0 ? lw : lw * 0.45));
        }
    }
    return vec2(ink, sil);
}

vec2 burst(vec2 p, float R, Scene s) {
    float n = floor(9.0 + 10.0 * h11(s.sd * 1.7));
    float m = mix(2.1, 3.2, h11(s.sd * 2.3));
    float r = length(p);
    float st = sdStar(rot(gT * 0.4 + gKick * 0.2) * p, R * (0.9 + 0.1 * gKick), n, m);
    float ink = max(st, -(r - R * 0.38));
    ink = min(ink, r - R * 0.28);
    ink = min(ink, abs(r - R * 1.1) - R * 0.022);
    return vec2(ink, r - R * 1.14);
}

vec2 butterfly(vec2 p, float R) {
    float flap = 0.72 + 0.28 * cos(gBeat * PI);
    p.x /= flap;
    vec2 q = vec2(abs(p.x), p.y);
    vec2 a = rot(-0.5) * (q - vec2(0.46, 0.24) * R);
    vec2 b = rot(0.6) * (q - vec2(0.3, -0.3) * R);
    float up = sdEll(a, vec2(0.46, 0.34) * R);
    float lo = sdEll(b, vec2(0.3, 0.22) * R);
    float body = sdEll(p - vec2(0.0, -0.02 * R), vec2(0.06, 0.42) * R);
    float shape = smin(smin(up, lo, 0.06 * R), body, 0.04 * R);
    shape = min(shape, sdSeg(q, vec2(0.02, 0.36) * R, vec2(0.16, 0.62) * R) - 0.016 * R);
    float holes = min(sdEll(a + vec2(0.03, 0.0) * R, vec2(0.27, 0.17) * R), sdEll(b, vec2(0.15, 0.1) * R));
    return vec2(max(shape, -holes), shape) * flap;
}

vec2 cubeProj(vec3 q, float a1, float a2, float R) {
    q.xz = rot(a1) * q.xz;
    q.yz = rot(a2) * q.yz;
    return q.xy * (3.0 / (4.0 + q.z)) * R * 0.62;
}
vec2 cube(vec2 p, float R, Scene s) {
    float d = 1e2;
    for (int c = 0; c < 2; c++) {
        float sc = c == 0 ? 1.0 : 0.5;
        float a1 = gT * (c == 0 ? 0.7 : -1.1) + s.sd, a2 = gT * (c == 0 ? 0.45 : -0.8) + 1.0;
        for (int e = 0; e < 12; e++) {                 // 4 edges along each axis
            float fe = float(e);
            float ax = floor(fe / 4.0);
            float j = fe - ax * 4.0;
            float u = mod(j, 2.0) * 2.0 - 1.0, v = floor(j / 2.0) * 2.0 - 1.0;
            vec3 ea = ax < 0.5 ? vec3(-1.0, u, v) : (ax < 1.5 ? vec3(u, -1.0, v) : vec3(u, v, -1.0));
            vec3 eb = ax < 0.5 ? vec3( 1.0, u, v) : (ax < 1.5 ? vec3(u,  1.0, v) : vec3(u, v,  1.0));
            d = min(d, sdSeg(p, cubeProj(ea * sc, a1, a2, R), cubeProj(eb * sc, a1, a2, R)));
        }
    }
    float ink = d - R * 0.02;
    return vec2(ink, ink);
}

vec2 swarm(vec2 p, float R, Scene s) {
    float ink = 1e2, sil = 1e2;
    for (int i = 0; i < 5; i++) {
        float fi = float(i);
        vec2 o = vec2(sin(gT * (0.6 + 0.13 * fi) + fi * 2.4 + s.sd), cos(gT * (0.47 + 0.11 * fi) + fi * 1.7)) * R * vec2(0.75, 0.7);
        float r = R * (0.22 + 0.1 * h11(fi + s.sd)) * (1.0 + 0.1 * gKick);
        vec3 sm = smileyShape(rot(sin(gT * 1.3 + fi) * 0.6) * (p - o), r, true);
        ink = min(ink, sm.x);
        sil = min(sil, sm.y);
    }
    return vec2(ink, sil);
}

vec2 vinyl(vec2 p, float R) {
    float r = length(p);
    float sil = r - R;
    float gs = R * 0.04;
    float a = atan(p.y, p.x);
    float shine = 1.0 - smoothstep(0.0, 0.3, abs(mod(a - 0.8 + PI * 0.5, PI) - PI * 0.5));
    float groove = abs(fract(r / gs + 0.5) - 0.5) * gs - gs * (0.1 + 0.25 * shine);
    groove = max(groove, max(R * 0.42 - r, r - R * 0.95));
    float ink = max(max(sil, -groove), -(r - R * 0.36));
    vec2 lp = rot(gT * 3.49) * p;                       // two-tone label spinning at 33 rpm
    ink = min(ink, max(r - R * 0.3, lp.y));
    ink = max(ink, -(length(lp - vec2(0.0, -0.16 * R)) - 0.045 * R));
    ink = min(ink, length(lp - vec2(0.0, 0.16 * R)) - 0.045 * R);
    ink = max(ink, -(r - R * 0.025));
    ink = min(ink, abs(r - R * 0.33) - R * 0.006);
    return vec2(ink, sil);
}

vec2 heroSD(vec2 p, float R, Scene s) {
    p = rot(0.15 * sin(gT * 0.9 + s.sd) * gChaos) * p;
    p *= 1.0 - 0.06 * gKick;
    if (s.hero == 0) return smileyShape(p, R, h11(s.sd * 4.4) < 0.5).xy;
    if (s.hero == 1) return globe(p, R, s);
    if (s.hero == 2) return burst(p, R, s);
    if (s.hero == 3) return butterfly(p, R);
    if (s.hero == 4) return cube(p, R, s);
    if (s.hero == 5) return swarm(p, R, s);
    return vinyl(p, R);
}

float echoRings(float d, vec2 p, float R) {   // wobbly contour echoes around a shape
    if (d <= 0.0) return 0.0;
    float sp = R * 0.1;
    float an = atan(p.y, p.x);
    float wob = (sin(an * 6.0 + gT * 3.0) * 0.3 + sin(an * 11.0 - gT * 4.0) * 0.15) * (0.4 + gChaos);
    float dd = d + wob * sp * smoothstep(0.0, R * 0.6, d);
    float ring = abs(fract(dd / sp - gT * 0.6 + 0.5) - 0.5) * sp;
    float lw = sp * 0.2 * smoothstep(sp * 0.3, sp * 1.1, dd) * (1.0 - smoothstep(sp * 4.0, sp * 6.0, dd));
    return lw > 0.0 ? fillD(ring - lw) : 0.0;
}

void drawHero(inout vec3 col, vec2 p, float R, Scene s, vec3 back, vec3 ink, vec3 ech, bool echo) {
    vec2 h = heroSD(p, R, s);
    if (echo) paint(col, ech, echoRings(h.y, p, R));
    paint(col, back, fillD(min(h.y, h.x - R * 0.03)));   // knock-out halo
    paint(col, ink, fillD(h.x));
}

// ====================================================================
//  PHOTO PANELS (halftoned crowd + lasers, or your own input)
// ====================================================================
float crowd(vec2 q, float asp, float sd, float ph) {    // q: x 0..asp, y 0..1
    float px = gPX / ph;
    float v = 0.25 + 0.45 * fbm(q * vec2(3.0, 2.0) + vec2(gT * 0.15, sd));
    vec2 dq = q - vec2(asp * (0.5 + 0.35 * sin(gT * 0.6 + sd)), 1.1);
    float fan = abs(fract(atan(dq.x, -dq.y) * 3.0 + gT * 0.5) - 0.5);
    v += (1.0 - smoothstep(0.02, 0.1, fan)) * (0.5 + 0.5 * gKick) * smoothstep(-0.2, 0.8, q.y);
    float sil = 1e2;
    for (int i = 0; i < 8; i++) {
        float fi = float(i);
        float x = ((fi + 0.5) / 8.0 + (h11(fi + sd * 13.0) - 0.5) * 0.08) * asp;
        float jump = abs(sin(gBeat * PI + fi * 1.3)) * 0.06;
        float y = 0.3 + h11(fi * 3.1 + sd) * 0.12 + jump;
        float r = 0.06 + 0.025 * h11(fi * 7.7 + sd);
        sil = min(sil, length((q - vec2(x, y)) * vec2(1.0, 0.85)) - r);
        sil = min(sil, sdRBox(q - vec2(x, y - r - 0.25), vec2(r * 1.7, 0.25), r));
        if (h11(fi * 5.3 + sd) > 0.45) {
            vec2 hand = vec2(x + 0.1 * sin(gT * 2.5 + fi), y + 0.28);
            sil = min(sil, sdSeg(q, vec2(x + r * 0.8, y - r), hand) - 0.02);
        }
    }
    return mix(v, 0.03, clamp(0.5 - sil / px, 0.0, 1.0));
}

// zine layout photo panels: top-left (top = true) or bottom-left, as (x0, y0, x1, y1)
vec4 photoRect(bool top) {
    float x0 = 0.052, iw = gW - 2.0 * x0;
    return top ? vec4(x0, 0.6, x0 + iw * 0.45, 1.0 - x0) : vec4(x0, x0, x0 + iw * 0.55, 0.318);
}

void photoPanel(inout vec3 col, vec2 P, vec4 rc, float sd) {
    vec2 a = rc.xy, b = rc.zw;
    float bd = sdBox(P - (a + b) * 0.5, (b - a) * 0.5);
    if (bd < 0.006) {
        float ph = b.y - a.y;
        float v = gPhoto >= 0.0 ? gPhoto : crowd((P - a) / ph, (b.x - a.x) / ph, sd, ph);
        paint(col, cI, halftone(P, v, 0.0085) * fillD(bd));
        paint(col, cI, strokeD(bd, 0.0016));
    }
}

