    vec2 ta = vec2(xa + g, ya + (y1 - ya) * 0.32), tb = vec2(x1, y1);
    paint(col, cI, fillD(sdRBox(P - (ta + tb) * 0.5, (tb - ta) * 0.5, 0.03)));
