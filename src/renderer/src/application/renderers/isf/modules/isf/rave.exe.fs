// ---- 5: zine grid - marquee border, halftone photos, outline type, barcodes ----
void gridRowB(vec2 P, Scene s, float x0, float iw, float yb0, float yb1, out int w, out vec2 org, out vec2 cs, out int i) {
    int qi = imod(s.quad + 1 + pickI(N_QUAD - 1, h11(s.sd)), N_QUAD);
    float lh = (yb1 - yb0) / 4.0;
    cs = vec2(min(iw * 0.74 / (quadMax(qi) - 1.0 / 6.0), lh * 0.86), lh * 0.86);
    i = int(clamp(floor((yb1 - P.y) / lh), 0.0, 3.0));
    w = G_QUAD + qi * 4 + i;
    org = vec2(x0, yb1 - lh * float(i + 1) + lh * 0.07);
}
void shapesGrid(inout vec3 col, vec2 P, Scene s) {
    float W = gW, m0 = 0.012, bw = 0.028;
    vec2 cp = vec2(min(P.x, W - P.x), min(P.y, 1.0 - P.y)) - vec2(m0 + bw * 0.5);
    paint(col, cI, fillD(sdStar(rot(gT) * cp, bw * 0.45, 4.0, 2.3)));
    float x0 = m0 + bw + 0.012, x1 = W - x0, y0 = x0, y1 = 1.0 - x0, iw = x1 - x0, g = 0.012;
    float ya = 0.6, xa = x0 + iw * 0.45, yb0 = 0.33, yb1 = ya - g, yc1 = yb0 - g, xc = x0 + iw * 0.55;
    paint(col, cI, strokeD(sdBox(P - vec2(W * 0.5, 0.5), vec2(W * 0.5 - x0 + 0.006, 0.5 - x0 + 0.006)), 0.0015));
    bool top = P.y > 0.45;
