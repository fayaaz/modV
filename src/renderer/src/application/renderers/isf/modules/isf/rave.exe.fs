void itemGrid(int k, vec2 P, Scene s) {
    float W = gW, m0 = 0.012, bw0 = 0.028;
    float x0 = m0 + bw0 + 0.012, x1 = W - x0, y0 = x0, y1 = 1.0 - x0, iw = x1 - x0, g = 0.012;
    float ya = 0.6, xa = x0 + iw * 0.45, yb0 = 0.33, yb1 = ya - g, yc1 = yb0 - g, xc = x0 + iw * 0.55;
    float tay = ya + (y1 - ya) * 0.32;                    // bottom of the title slab
    vec2 p = P, anc = vec2(0.0), aln = vec2(0.0);
    float bw = 1e3, bh = 1.0, st = 1e3, cxm = 1.0;        // fixed cells unless set
    int w = -1, sty = 0;
    vec3 col = cI;
    if (k == 0) {                                         // marquee crawling around the border
        float dl = P.x, dr = W - P.x, db = P.y, dt = 1.0 - P.y;
        float e = min(min(dl, dr), min(db, dt));
        float sa = e == dt ? P.x : (e == dr ? W + 1.0 - P.y : (e == db ? 2.0 * W + 1.0 - P.x : 2.0 * W + 1.0 + P.y));
        float ch = bw0 * 0.72;
        p = vec2(sa, m0 + bw0 - e); anc = vec2(0.0, (bw0 - ch) * 0.5); cxm = ch / 1.25; bh = ch;
        w = (e < m0 || e > m0 + bw0 || (min(dl, dr) < m0 + bw0 && min(db, dt) < m0 + bw0)) ? -1 : s.marq;
        gTScr = gT * 2.5; gTRep = true;
    } else if (k == 1) {                                  // title slab, right aligned
        float lh = (y1 - tay - 0.02) / 4.0;
        float i = clamp(floor((y1 - 0.01 - P.y) / lh), 0.0, 3.0);
        anc = vec2(x1 - 0.015, y1 - 0.01 - lh * (i + 1.0) + lh * 0.06); aln = vec2(1.0, 0.0);
        cxm = min((x1 - xa - g - 0.03) / (quadMax(s.quad) - 1.0 / 6.0), lh * 0.8); bh = lh * 0.88;
        w = P.x < xa + g ? -1 : G_QUAD + s.quad * 4 + int(i); col = cP;
    } else if (k == 2) {                                  // info strip, three small lines
        float ihy = (tay - g - ya) * 0.5, lx = xa + g + 0.008;
        float i = clamp(floor((tay - g - ihy * 0.12 - P.y) / (ihy * 0.6)), 0.0, 2.0);
        int ii = int(i);
        anc = vec2(lx, tay - g - ihy * 0.12 - ihy * 0.6 * (i + 1.0));
        bw = x1 - ihy * 1.75 - 0.01 - lx; bh = ihy * 0.4; st = 1.3; cxm = bh / st;
        w = (P.x < xa + g || P.y < ya || P.y > tay - g) ? -1 : (ii == 0 ? s.tag : (ii == 1 ? s.i0 : s.hour));
    } else if (k == 3) {                                  // outlined lines (+ barcode in the renderer)
        int ww, i; vec2 org, cs;
        gridRowB(P, s, x0, iw, yb0, yb1, ww, org, cs, i);
        anc = org; cxm = cs.x; bh = cs.y; sty = 2;
        w = (P.y < yb0 || P.y > yb1) ? -1 : ww;
    } else {                                              // NO SLEEP stack, scrolling
        vec2 na = vec2(xc + g, y0), nb = vec2(x1, yc1);
        float lh = (nb.y - na.y) / 6.0;
        float yy = P.y - na.y + gT * 0.5 * lh;
        p = vec2(P.x, yy - floor(yy / lh) * lh); anc = vec2(na.x + 0.008, lh * 0.5); aln = vec2(0.0, 0.5);
        bw = nb.x - na.x - 0.016; cxm = 1e3; bh = lh * 0.84; st = 1.8;
        w = W_NOSLEEP; gTA = fillD(sdBox(P - (na + nb) * 0.5, (nb - na) * 0.5) + 0.003);
    }
    tItem(p, anc, aln, w, vec4(bw, cxm, bh, st), sty, col);
}

// which text item (if any) can cover this pixel - text lines never overlap
int textSlot(vec2 P, Scene s) {
    float W = gW, sc = min(W / 0.8, 1.0);
    if (s.lay == 0) {
        if (P.y > 0.6) return 0;
        if (length(P - vec2(W - 0.035 - 0.075 * sc, 0.29)) < 0.09 * sc) return 5;
        if (P.y > 0.135) return 1;
        if (P.y > 0.088) return 2;
        if (P.y > 0.045) return 3;
        return 4;
    }
    if (s.lay == 1) {
        if (P.y > 0.935) return 0;
        if (P.y > 0.8) return 1;
        if (P.y > 0.26) return 2;
        if (P.y > 0.18) return 3;
        if (P.y > 0.128) return 4;
        if (P.y > 0.08) return 5;
        if (P.y > 0.045) return 6;
        return 7;
    }
    if (s.lay == 2) return P.y > 0.86 ? 1 : (P.x > W * 0.48 ? 0 : 2);
    if (s.lay == 3) {
        if (length(P - vec2(W * 0.5, 0.53)) < min(W * 0.47, 0.44) * 1.05) return 0;
        if (P.y > 0.9) return 2;
        return P.x > W * 0.5 ? 1 : 3;
    }
    if (s.lay == 4) {
        float sx0 = W * 0.76, sw = W - 0.03 - sx0;
        if (P.x > sx0) return P.x < sx0 + sw * 0.69 ? 0 : 1;
        return P.y > 0.85 ? 3 : 2;
    }
    float m0 = 0.012, bw = 0.028, x0 = m0 + bw + 0.012;        // 5: zine grid
    if (min(min(P.x, W - P.x), min(P.y, 1.0 - P.y)) < m0 + bw + 0.004) return 0;
    if (P.y > 0.594) return P.y > 0.6 + (0.4 - x0) * 0.32 ? 1 : 2;
    return P.y > 0.33 ? 3 : 4;
}

void textItem(int k, vec2 P, Scene s) {
    if (s.lay == 0) itemHeader(k, P, s);
    else if (s.lay == 1) itemWicked(k, P, s);
    else if (s.lay == 2) itemAcid(k, P, s);
    else if (s.lay == 3) itemSmiley(k, P, s);
    else if (s.lay == 4) itemVertical(k, P, s);
    else itemGrid(k, P, s);
}

vec3 renderScene(vec2 P, float id) {
    Scene s = makeScene(id);
    // chaos: re-roll pieces of the poster on the beat
    float bt = floor(gBeat), b2 = floor(gBeat * 0.5);
    if (h21(vec2(bt, id + 0.5)) < gChaos * 0.4) s.head = G_HEAD + pickI(N_HEAD, h21(vec2(bt, id + 1.5)));
    if (h21(vec2(bt, id + 2.5)) < gChaos * 0.3) s.sty = pickI(5, h21(vec2(bt, id + 3.5)));
    if (h21(vec2(b2, id + 4.5)) < gChaos * 0.3) s.pal = pickI(12, h21(vec2(b2, id + 5.5)));
    if (h21(vec2(floor(gBeat * 2.0), id + 6.5)) < gChaos * 0.12) s.inv = !s.inv;
    if (s.lay == 0 && h21(vec2(b2, id + 7.5)) < gChaos * 0.35) s.hero = pickI(7, h21(vec2(b2, id + 8.5)));
    if (s.lay == 0 && h21(vec2(b2, id + 9.5)) < gChaos * 0.3) s.bg = sel(pickI(6, h21(vec2(b2, id + 10.5))), 0, 1, 2, 3, 4, 6, 6);
    setPal(s.pal, s.inv);

    float W = gW, cx = W * 0.5, sc = min(W / 0.8, 1.0), sx0 = W * 0.76;
    vec3 col = cP;
    if (s.lay != 5) {                                             // shared background
        vec2 bc = s.lay == 1 ? vec2(cx, 0.6) : (s.lay == 2 ? vec2(cx, 0.56) : (s.lay == 4 ? vec2(W * 0.4, 0.55) : vec2(cx, 0.49)));
        vec2 bg = background(P - bc, s.bg, s.sd);
        vec3 bcol = s.lay == 1 ? mix(cP, cI, 0.16) : (s.lay == 3 ? cA : mix(cI, cA, bg.y));
        paint(col, bcol, bg.x * (s.lay == 3 ? 0.7 : 1.0));
    }
    if (s.lay == 0 || s.lay == 1 || s.lay == 4) {                 // shared hero
        vec2 hc = s.lay == 0 ? vec2(cx, 0.49) : (s.lay == 1 ? vec2(cx, 0.6) : vec2(sx0 * 0.5, 0.56));
        float R = s.lay == 0 ? 0.23 * sc : (s.lay == 1 ? 0.19 * sc : min(sx0 * 0.42, 0.3));
        vec3 ink = s.lay == 4 ? accOn() : cI;
        drawHero(col, P - hc, R, s, cP, ink, ink, s.echo);
    }
    if (s.lay == 0) shapesHeader(col, P, s);
    else if (s.lay == 1) shapesWicked(col, P, s);
    else if (s.lay == 2) shapesAcid(col, P, s);
    else if (s.lay == 4) shapesVertical(col, P, s);
    else if (s.lay == 5) shapesGrid(col, P, s);

    gTScr = 0.0; gTWob = 0.0; gTA = 1.0; gTRep = false; tW = -1;
    int slot = textSlot(P, s);
    textItem(slot, P, s);                                         // the one text line here
    if (tW >= 0 && gTA > 0.0) {
        vec2 wi = wordInfo(float(tW));
        float L1 = wi.y - 1.0 / 6.0;
        float cxs = min(tSz.x / L1, tSz.y);
        vec2 cs = vec2(cxs, min(tSz.z, cxs * tSz.w));
        vec2 org = tAnc - vec2(L1 * cs.x, cs.y) * tAln;
        vec2 p = tP;
        p.y += sin(p.x * 18.0 + gT * 5.0) * cs.y * 0.05 * gChaos * gTWob;
        vec3 sh = styShape(tSty);
        vec2 off = vec2(0.9, -0.7) * (1.0 + 1.5 * gKick) * cs / vec2(6.0, 5.0);
        for (int k = 0; k < 2; k++) {                             // 0: style-4 drop shadow, 1: ink
            if (k == 0 && tSty != 4) continue;
            float d = sdText(k == 0 ? p - off : p, org, cs, wi.x, wi.y, gTScr, gTRep, sh);
            paint(col, k == 0 ? cA : tCol, (k == 0 ? fillD(d) : textMask(d, tSty, cs)) * gTA);
        }
        if (s.lay == 5 && slot == 3) {                            // zine: barcode trailing the outline type
            float u = 0.0035, bx0 = org.x + L1 * cs.x + 0.014;
            if (P.x > bx0 && P.x < gW - 0.052 && P.y > org.y && P.y < org.y + cs.y) {
                float bxx = (P.x - bx0) / u + floor(gT * 6.0) * 3.0 * gChaos;
                float hb = h21(vec2(floor(bxx), org.y * 97.0 + s.sd));
                float wf = hb > 0.45 ? 0.3 + 0.6 * h11(hb * 91.0) : 0.0;
                paint(col, cI, wf > 0.0 ? fillD((abs(fract(bxx) - 0.5) - 0.5 * wf) * u) : 0.0);
            }
        }
    }
    return col;
}

// ====================================================================
//  ENTRY:  fragCoord / res in pixels, tm in seconds.
//  firstIn = poster shown at tm = 0, holdIn = stay on that poster,
//  layIn = force a layout 0..5 (< 0 = generator picks).
// ====================================================================
vec3 rave(vec2 fragCoord, vec2 res, float tm, float bpmIn, float chaosIn, float seedIn, float kickIn, float firstIn, bool holdIn, int layIn) {
    gT     = tm;
    gBeat  = tm * bpmIn / 60.0;
    gChaos = clamp(chaosIn, 0.0, 1.0) * smoothstep(0.0, 2.0, gBeat);   // calm first frame (poster grabs)
    gLay   = layIn;
    // portrait / square canvases are the poster; wider ones hang a 4:5 poster on a wall
    float asp = res.x / res.y;
    bool wall = asp > 1.05;
    float ps = wall ? 0.92 : 1.0;
    gW  = wall ? 0.8 : asp;
    gPX = 1.0 / (res.y * ps);
    vec2 Q  = vec2((fragCoord.x / res.x - 0.5) * asp, fragCoord.y / res.y - 0.5);
    vec2 P  = Q / ps + vec2(gW * 0.5, 0.5);
    vec2 uv = P / vec2(gW, 1.0);                                  // poster-relative 0..1

    gPhoto = -1.0;                                                // sample the photo input up front,
#ifdef RAVE_INPUT                                                 // outside any branch or loop
    vec4 pr = photoRect(P.y > 0.45);
    gPhoto = RAVE_INPUT(clamp((P - pr.xy) / (pr.zw - pr.xy), 0.0, 1.0));
#endif

    float s16 = floor(gBeat * 4.0);
    if (h11(s16 * 2.71 + 0.3) < gChaos * 0.12) {                 // stutter: freeze on a 16th
        gBeat = s16 * 0.25;
        gT = gBeat * 60.0 / bpmIn;
    }
    gKick = max(exp(-fract(gBeat) * 6.0), clamp(kickIn, 0.0, 1.0));

    vec2 ctr = vec2(gW * 0.5, 0.5);                               // kick punch + shake
    P = ctr + (P - ctr) / (1.0 + 0.035 * gKick * gChaos);
    P += (h22(vec2(mod(floor(gT * 24.0), 997.0), 1.0)) - 0.5) * 0.006 * gChaos * gKick;
    gRough = (vnoise(P * 520.0 + mod(floor(gT * 12.0), 500.0) * 7.13) - 0.5) * 2.2 * gPX * (0.5 + gChaos);

    // new poster every 2 bars; the last beat flickers with the next one
    float sid = floor(firstIn) + floor(seedIn) * 101.0;
    if (!holdIn) {
        sid += floor(gBeat / 8.0);
        if (mod(gBeat, 8.0) > 7.0 && h11(s16 * 1.31) < 0.3 + 0.6 * gChaos) sid += 1.0;
    }

    bool split = false;                                           // horizontal tear bands
    if (h11(s16 * 0.731 + 3.7) < gChaos * 0.5) {
        float nb = floor(mix(5.0, 28.0, h11(s16 + 9.1)));
        float band = floor(uv.y * nb);
        float hb = h21(vec2(band, s16));
        if (hb < 0.15 + 0.3 * gChaos) {
            P.x += (h21(vec2(band, s16 + 1.0)) - 0.5) * 0.3 * gChaos;
            if (hb < 0.1 * gChaos + 0.03) sid += floor(1.0 + h21(vec2(band, s16 + 2.0)) * 5.0);
            split = hb > 0.12;
        }
    }

    vec3 col = renderScene(P, sid);
    if (split) col = mix(col, col.gbr, 0.7);                      // misprinted ink in the tears

    float s8 = floor(gBeat * 2.0);                                // block inversions
    for (int i = 0; i < 3; i++) {
        float fi = float(i);
        vec4 hb = vec4(h21(vec2(s8, fi)), h21(vec2(s8, fi + 0.5)), h21(vec2(s8, fi + 0.7)), h21(vec2(s8, fi + 0.9)));
        if (hb.x < gChaos * 0.3) {
            vec2 a = hb.yz * vec2(gW, 1.0) - 0.1;
            vec2 sz = vec2(0.1 + 0.4 * hb.w, 0.015 + 0.09 * hb.y);
            if (all(greaterThan(P, a)) && all(lessThan(P, a + sz))) col = 1.0 - col;
        }
    }
    if (fract(gBeat / 4.0) < 0.035 && h11(floor(gBeat / 4.0) + 0.3) < gChaos * 0.5) col = 1.0 - col;   // downbeat strobe

    // print finish: grain, paper mottle, fold creases, vignette
    col += (h21(fragCoord + fract(gT * 13.7) * vec2(97.0, 53.0)) - 0.5) * 0.05;
    col *= 0.93 + 0.07 * fbm(uv * vec2(gW, 1.0) * 5.0 + seedIn);
    float cr = exp(-abs(uv.x - 0.5) * 500.0) + 0.7 * (exp(-abs(uv.y - 0.333) * 500.0) + exp(-abs(uv.y - 0.666) * 500.0));
    col *= (1.0 - 0.07 * cr) * (1.0 + 0.015 * sign(uv.x - 0.5));
    col *= 1.0 - 0.2 * pow(length(uv - 0.5) * 1.25, 2.5);
    if (wall) {                                                   // dark wall + drop shadow
        vec2 hw = vec2(gW * 0.5, 0.5);
        vec3 wc = vec3(0.075, 0.07, 0.068) * (0.75 + 0.5 * vnoise(Q * 40.0)) * (1.0 - 0.5 * length(Q));
        wc *= 1.0 - 0.55 * exp(-max(sdBox(P - hw - vec2(0.012, -0.018), hw), 0.0) * 40.0);
        col = mix(wc, col, clamp(0.5 - sdBox(P - hw, hw) / gPX, 0.0, 1.0));
    }
    return clamp(col, 0.0, 1.0);
}

void main() {
    vec3 c = rave(isf_FragNormCoord.xy * RENDERSIZE, RENDERSIZE, TIME, bpm, chaos, seed, kick, firstPoster, holdPoster, layoutLock);
    gl_FragColor = vec4(c, 1.0);
}
