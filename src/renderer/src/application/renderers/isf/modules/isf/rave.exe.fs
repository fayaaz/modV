// Text items are table-style: branches only set the few values that differ,
// then one tItem() call (branches that compute whole items each cost the
// WebGL compiler ~0.2 s; branches that pick values are nearly free).
// Fitted text: sz = (bw, bh / st, bh, st). Fixed cell: (1e3, cell w, cell h, 1e3).
void itemHeader(int k, vec2 P, Scene s) {
    float W = gW, cx = W * 0.5, m = 0.035, sc = min(W / 0.8, 1.0);
    vec2 p = P, anc = vec2(cx, 0.068), aln = vec2(0.5);
    float bw = W - 2.0 * m, bh = 0.022, st = 1.3, cxm = -1.0;
    int w = s.i1, sty = 0;
    vec3 col = cI;
    if (k == 0) { anc.y = 0.875; bw = (cx - m) * 1.84; bh = 0.13; w = s.head; sty = s.sty; col = cP; gTWob = 1.0; }
    else if (k == 1) { anc.y = 0.162; bh = 0.038; w = s.tag; }
    else if (k == 2) { anc.y = 0.108; bh = 0.026; w = s.i0; }
    else if (k == 4) {                                    // lineup ticker
        anc = vec2(m, 0.016); aln = vec2(0.0); bw = 1e3; cxm = 0.0125; bh = 0.016; st = 1e3; w = W_LINEUP; col = accOn();
        gTScr = gT * 3.0; gTRep = true; gTA = fillD(abs(P.x - cx) - (cx - m));
    } else if (k == 5) {                                  // year on the sticker
        p = rot(-0.25) * (P - vec2(W - m - 0.075 * sc, 0.29)); anc = vec2(0.0);
        bw = 0.084 * sc; bh = 0.042 * sc; st = 1.2; w = s.yr; col = inkOn(cA);
    }
    tItem(p, anc, aln, w, vec4(bw, cxm < 0.0 ? bh / st : cxm, bh, st), sty, col);
}

