// ---- 2: acid - box tunnel, coin smileys, waving word stack, info box ----
void shapesAcid(inout vec3 col, vec2 P, Scene s) {
    float W = gW, m = 0.035, sc = min(W / 0.8, 1.0);
    vec2 cq = P - vec2(m, 0.36);                                  // fading checker strip
    if (cq.x > 0.0 && cq.x < W * 0.44 && cq.y > 0.0 && cq.y < 0.1) {
        vec2 g = cq / 0.025 + vec2(gT * 1.5, 0.0);
        float fw = PI / 0.025 * gPX;
        float v = clamp(sin(g.x * PI) / fw, -1.0, 1.0) * clamp(sin(g.y * PI) / fw, -1.0, 1.0);
        paint(col, accOn(), (0.5 + 0.5 * v) * (1.0 - smoothstep(0.0, W * 0.44, cq.x)));
    }
    for (int i = 0; i < 2; i++) {                                 // tumbling coin smileys
        float fi = float(i);
        vec2 c = vec2(W * (0.22 + 0.1 * fi), 0.64 - 0.17 * fi) + vec2(sin(gT * 0.9 + fi * 2.0), cos(gT * 0.7 + fi)) * 0.03;
        float R = (i == 0 ? 0.13 : 0.095) * sc * (1.0 + 0.06 * gKick);
        float tilt = sin(gT * 1.2 + fi * 1.7) * 0.9;
        vec2 p = rot(0.4 * sin(gT * 0.8 + fi)) * (P - c);
        p.x /= max(cos(tilt), 0.25);
        paint(col, cA, fillD(smileyShape(p + vec2(sin(tilt) * 0.16, -0.1) * R, R, true).y));
        vec3 sm = smileyShape(p, R, true);
        paint(col, cI, fillD(sm.y));
        paint(col, cP, fillD(max(sm.z, sm.y)));
    }
    float tbd = sdRBox(P - vec2(W * 0.5, 0.93), vec2(W * 0.5 - m, 0.026), 0.008);   // window bar
    paint(col, cP, fillD(tbd));
    paint(col, cI, strokeD(tbd, 0.002));
    vec2 xp = P - vec2(W - m - 0.022, 0.93);
    paint(col, cI, fillD(min(sdSeg(xp, vec2(-0.008), vec2(0.008)), sdSeg(xp, vec2(-0.008, 0.008), vec2(0.008, -0.008))) - 0.0018));
    vec2 b0 = vec2(m, 0.05), b1 = vec2(W * 0.46, 0.33);           // info box
    float bd = sdRBox(P - (b0 + b1) * 0.5, (b1 - b0) * 0.5, 0.012);
    paint(col, cP, fillD(bd));
    paint(col, cI, strokeD(bd, 0.0022));
    for (int i = 0; i < 3; i++) {                                 // sparkles
        float fi = float(i);
        float r = 0.022 * (0.7 + 0.5 * abs(sin(gT * 2.0 + fi * 2.0)));
        paint(col, accOn(), fillD(sdStar(P - vec2(W * (0.52 + 0.17 * fi), 0.86 - 0.05 * fi), r, 4.0, 2.3)));
    }
}

