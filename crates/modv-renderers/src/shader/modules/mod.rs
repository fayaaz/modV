//! The built-in shader module registry — every module the Gallery ships,
//! ported from `src/renderer/src/application/renderers/shader/modules/`.
//!
//! # Count (37)
//!
//! | Flavour | Count | Modules |
//! |---------|-------|---------|
//! | direct (`gl_FragColor` → own `fs_main`) | 5 | Bands, Fisheye, MattiasCRT, Plasma, Wobble |
//! | mainImage shim (`mainImage` + wrapper) | 32 | Chromatic Abberation, 31 × Point10 |
//!
//! # Registration order
//!
//! [`all_modules`] preserves the JS registration order: the six
//! single-effect modules first (in `modules/` directory listing order),
//! then the Point10 effects in the order they appear in
//! `Point10Effects.js`. Gallery order changes only deliberately.
//!
//! # Prop-buffer contract
//!
//! Each module's WGSL declares its own `ModuleProps` struct at binding 7
//! (generated by `module_props_wgsl` in `super::uniforms`) with one
//! 16-byte slot per prop, in **declaration order** — the same order the
//! engine must encode into [`crate::shader::uniforms::PropSlots`]. The
//! in-tree modules only declare `float` props.
//!
//! # Wrapper path per module
//!
//! The `mainImage` rule is the JS rule (`index.js:140`): a fragment source
//! **without** `gl_FragColor` is wrapped in the `DEFAULT_MAINIMAGE_WRAP`
//! shim. The port hard-codes that decision in the source files — Bands,
//! Fisheye, MattiasCRT, Plasma and Wobble are built with
//! [`direct_fragment`](crate::shader::default_shader::direct_fragment),
//! everything else with
//! [`main_image_fragment`](crate::shader::default_shader::main_image_fragment).
//!
//! # preview_with_output
//!
//! Ported from `meta.previewWithOutput`: `true` everywhere except **Bands**
//! and **Plasma**, which do not set it in their JS meta.
//!
//! # audio / audio_features
//!
//! `audio = true` means the module requests meyda features — ported from
//! `meta.audioFeatures`. Bands requests `["bass", "mid", "treble"]` and so
//! do the four audio Point10 effects (Contrast, Color Distort, RGB Shift,
//! Digital Glitch). Note this diverges from the shorthand "audio=true only
//! for the four Point10 effects" note in the work order — Bands' JS meta
//! unmistakably requests audio, and dropping it would leave the rings
//! static. `audio_features` carries the exact list for the engine.
//!
//! # Chromatic Abberation keeps the JS spelling
//!
//! The Gallery meta name is "Chromatic Abberation" (that exact, misspelled
//! name) — kept verbatim so presets and Gallery defaults keep matching.
//! MattiasCRT's JS file is `MattiasCRT-2.0.js` but registers as
//! "MattiasCRT".

#![forbid(unsafe_code)]

use crate::shader::uniforms::ShaderProp;

mod bands;
mod chromatic_abberation;
mod fisheye;
mod mattias_crt;
mod plasma;
mod point10_effects;
mod wobble;

/// A registered built-in shader module.
///
/// The public `ShaderModule` is the registry's wire format: it carries the
/// final WGSL string (prelude + wrapper already expanded) plus the meta
/// needed to file it in the Gallery. It is **not** `Clone`-free on purpose —
/// pipelines are built from it once at registration and the buffers live on
/// the engine side.
pub struct ShaderModule {
    /// Gallery registration name, as it appears in presets and the Gallery
    /// (e.g. `Bands`, `Point10 Gray`).
    pub name: &'static str,
    /// Final WGSL fragment source — shared prelude already expanded, the
    /// mainImage wrapper already applied for mainImage-flavour modules.
    pub fragment_wgsl: String,
    /// JS `meta.author`.
    pub meta_author: &'static str,
    /// JS `meta.version`, stringified.
    pub meta_version: &'static str,
    /// JS `meta.category`, or `None` to fall back to type-based Gallery
    /// placement (`shader` → Effects). Only Bands sets one.
    pub category: Option<&'static str>,
    /// `true` when the module requests meyda features. Port of
    /// `meta.audioFeatures` presence.
    pub audio: bool,
    /// Port of `meta.audioFeatures`; empty when the module does not
    /// request audio features.
    pub audio_features: &'static [&'static str],
    /// Port of `meta.previewWithOutput`.
    pub preview_with_output: bool,
    /// Module props in declaration order — the prop-buffer slot order.
    pub props: Vec<ShaderProp>,
}

/// All 37 built-in shader modules, in registration order.
///
/// Always returns freshly built values (the fragment sources are
/// `format!`-expanded at call time — cheap, once per activation).
pub fn all_modules() -> Vec<ShaderModule> {
    let mut modules = Vec::with_capacity(37);
    modules.push(bands::module());
    modules.push(chromatic_abberation::module());
    modules.push(fisheye::module());
    modules.push(mattias_crt::module());
    modules.push(plasma::module());
    modules.push(wobble::module());
    modules.extend(point10_effects::modules());
    modules
}

/// The number of built-in modules; asserted by the tests below.
pub const MODULE_COUNT: usize = 37;

/// Compose a module's fragment body with its generated `ModuleProps`
/// declaration (or nothing, for prop-less modules). Keeps the WGSL member
/// order, the Rust [`PropLayout`](crate::shader::uniforms::PropLayout)
/// offsets and the shader's `props.*.x` reads derived from a single source
/// of truth — the module's prop list.
pub(crate) fn fragment_with_props(body: &str, props: &[ShaderProp]) -> String {
    match crate::shader::uniforms::module_props_wgsl(props) {
        Some(props_wgsl) => format!("{props_wgsl}\n{body}"),
        None => body.to_string(),
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::shader::default_shader::validate_wgsl;

    #[test]
    fn module_count_is_37() {
        assert_eq!(all_modules().len(), MODULE_COUNT);
    }

    #[test]
    fn modules_register_unique_names() {
        let modules = all_modules();
        let mut names = Vec::with_capacity(modules.len());
        for module in &modules {
            assert!(
                !names.contains(&module.name),
                "duplicate module registration name: {:?}",
                module.name
            );
            names.push(module.name);
        }
    }

    #[test]
    fn all_shader_modules_parse_and_validate_with_naga() {
        // The full wgpu-equivalent gate: front-end parse plus the naga
        // validator (including the uniform control-flow pass that any
        // implicit-derivative textureSample would fail).
        for module in all_modules() {
            validate_wgsl(&module.fragment_wgsl).unwrap_or_else(|error| {
                panic!("module {:?} failed WGSL validation: {error}", module.name)
            });
        }
    }

    #[test]
    fn wrapper_path_modules_use_mainimage() {
        let modules = all_modules();
        let with_main_image = modules
            .iter()
            .filter(|module| module.fragment_wgsl.contains("mainImage"));
        assert_eq!(
            with_main_image.count(),
            32,
            "exactly the 31 Point10 effects and Chromatic Abberation use the mainImage shim"
        );
    }

    #[test]
    fn glsl_fragcolor_modules() {
        // The five modules whose GLSL wrote gl_FragColor must return a vec4
        // from their own fs_main — no mainImage anywhere in the source.
        let direct = ["Bands", "Fisheye", "MattiasCRT", "Plasma", "Wobble"];
        for module in all_modules() {
            if direct.contains(&module.name) {
                assert!(
                    !module.fragment_wgsl.contains("mainImage"),
                    "module {:?} must not contain mainImage",
                    module.name
                );
                assert!(
                    module.fragment_wgsl.contains("fs_main"),
                    "module {:?} must declare fs_main",
                    module.name
                );
            }
        }
    }

    #[test]
    fn point10_modules_consume_builtins_only() {
        // The 31 Point10 effects request no props, and all of them opt into
        // preview-with-output, like the JS meta.
        let modules = all_modules();
        let point10 = modules
            .iter()
            .filter(|module| module.name.starts_with("Point10 "));
        assert_eq!(point10.clone().count(), 31);
        for module in point10 {
            assert!(
                module.props.is_empty(),
                "Point10 module {:?} must not declare props",
                module.name
            );
            assert!(
                module.preview_with_output,
                "Point10 module {:?} must set previewWithOutput",
                module.name
            );
            assert_eq!(module.category, None);
            assert_eq!(module.meta_author, "Point10");
            assert_eq!(module.meta_version, "1.0.0");
        }
    }

    #[test]
    fn preview_with_output_matches_js_meta() {
        let modules = all_modules();
        for module in &modules {
            let expected = !matches!(module.name, "Bands" | "Plasma");
            assert_eq!(
                module.preview_with_output, expected,
                "preview_with_output mismatch for {:?}",
                module.name
            );
        }
    }

    #[test]
    fn audio_features_match_js_meta() {
        let modules = all_modules();
        for module in &modules {
            let expected_features: &[&str] = match module.name {
                "Bands"
                | "Point10 Contrast"
                | "Point10 Color Distort"
                | "Point10 RGB Shift"
                | "Point10 Digital Glitch" => &["bass", "mid", "treble"],
                _ => &[],
            };
            assert_eq!(
                module.audio_features, expected_features,
                "audio_features mismatch for {:?}",
                module.name
            );
            assert_eq!(
                module.audio,
                !module.audio_features.is_empty(),
                "audio flag mismatch for {:?}",
                module.name
            );
        }
    }
}
