//! ISF renderer — port of `src/renderer/src/application/renderers/isf/`.
//! See docs/rust-hybrid.md, "WS-4 ISF renderer".
//!
//! The vendored JavaScript implementation is the npm package
//! `interactive-shader-format` (a fork of `vcync/interactive-shader-format-js`)
//! plus modV's own `index.js` and `float-buffer-support.js`. This module
//! reimplements the parts the renderer needs, in four layers plus a runtime:
//!
//! | Module | Replaces | Responsibility |
//! |--------|----------|----------------|
//! | [`parser`] | `MetadataExtractor`, `ISFParser.parse`, `ISFUpgrader` | header JSON, inputs, passes, v1 upgrade |
//! | [`source`] | `ISFParser.fragmentShaderSkeleton`/`vertexShaderSkeleton`/`replaceSpecialFunctions` | ISF macro expansion, uniform block, ES → desktop 450 |
//! | [`translate`] | — | naga GLSL → WGSL, overrides, tracked corpus report |
//! | [`props`] | `renderers/isf/index.js:181-281`, `module-category.js` | input → modV prop synthesis, metadata |
//! | [`runtime`] | `ISFRenderer`, `ISFBuffer`, `ISFTexture`, `float-buffer-support.js` | multi-pass wgpu execution, persistent/float buffers |
//!
//! # Why a translator at all
//!
//! The corpus is 351 `.fs` files (36 with a `.vs` sidecar), 63 multi-pass
//! shaders, 43 with `PERSISTENT` buffers, 288 with an `image` input. Hand
//! porting them is not an option; `docs/isf-translation-notes.md` records the
//! verified path: preprocess ES → desktop GLSL 450, then use naga's GLSL
//! front-end. The translation rate is tracked in `docs/isf-corpus-report.md`,
//! regenerated by the test in [`translate`].
//!
//! # Runtime contract (what a WGSL override must match)
//!
//! * `@group(0) @binding(0)` — the `IsfUniforms` uniform block, dynamic
//!   offset, one 256-byte slice per pass. Its members are generated by
//!   [`source::uniform_members`]; offsets follow WGSL uniform rules
//!   ([`source::uniform_layout`]).
//! * `@group(0) @binding(2*i+1)` — `texture_2d<f32>` and
//!   `@binding(2*i+2)` — `sampler`, in [`source::texture_inputs`] order
//!   (image/audio inputs first, then pass targets).
//! * Entry point `main`, returning `@location(0) vec4<f32>`.
//!
//! # Deviations from the Electron renderer (all deliberate)
//!
//! * **Coordinates.** wgpu's `@builtin(position)` and texture `v = 0` are
//!   top-left; GL's are bottom-left. `isf_FragNormCoord` is top-left origin,
//!   so texture sampling is visually identical while shaders that treat it as
//!   a Cartesian coordinate are mirrored. `gl_FragCoord` is top-left too.
//! * **`isf_FragCoord`.** The vendored vertex skeleton writes a differently
//!   cased `isf_fragCoord` that is never declared as an output, so reading it
//!   in a fragment shader would be a link error. The preprocessor defines it
//!   as `floor(gl_FragCoord.xy)` instead.
//! * **`bool` uniforms.** WGSL forbids `bool` in a uniform block, so bool and
//!   event inputs travel as `int isf_bool_<name>` and are copied into private
//!   `bool <name>` globals at the top of the entry point (a `bool()` macro
//!   would rewrite `.r` swizzles for the corpus' input named `r`).
//!   `_<name>_flip` is an `int` for the same reason.
//! * **Unbound fragment varyings.** 37 corpus shaders carry template-leftover
//!   `in`/`varying` declarations (`left_coord`, `texOffsets[5]`, …). The
//!   preprocessor strips the storage qualifier so they become zero-initialised
//!   private globals, mirroring what the GLSL compiler does with unused
//!   inputs. The runtime always draws the built-in full-screen triangle, so
//!   translated `.vs` sidecars are report-only for now.
//! * **`CLEAR`** is honoured (ISF v2 default true) even though the vendored
//!   `ISFParser` ignores it; with a full-screen triangle it only affects
//!   whether the target is cleared first.
//! * **Lowercase pass keys** (`"persistent"` in three corpus shaders) are
//!   accepted case-insensitively; JavaScript silently dropped them.
//!
//! # Not in this crate
//!
//! Prop coercion/clamping and input links (WS-1) stay in the engine; the
//! runtime takes coerced [`runtime::IsfValues`]. Gallery/preview context
//! separation is expressed by compiling per target format and drawing into
//! different targets, not by two GL contexts.

