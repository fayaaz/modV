//! Embed `src/isf/overrides/*.wgsl` into the binary (review item R-27).
//!
//! The directory is the single source of truth: every `.wgsl` file in it is
//! pulled into the crate with `include_str!`, so a packaged engine carries the
//! overrides without shipping a data directory next to the executable
//! (`electron-builder.yml` is untouched). Adding or editing an override only
//! needs a rebuild — `cargo:rerun-if-changed` on the directory handles that.
//!
//! The generated table is `EMBEDDED_OVERRIDES: &[(&str, &str)]` of
//! `(shader_name, source)` pairs, included by [`mod@crate::isf::translate`].

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

fn main() {
    let manifest_dir = PathBuf::from(
        std::env::var_os("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR is set by cargo"),
    );
    let overrides_dir = manifest_dir.join("src").join("isf").join("overrides");
    println!("cargo:rerun-if-changed={}", overrides_dir.display());

    let mut files: Vec<PathBuf> = match std::fs::read_dir(&overrides_dir) {
        Ok(entries) => entries
            .flatten()
            .map(|entry| entry.path())
            .filter(|path| {
                path.extension()
                    .is_some_and(|extension| extension == "wgsl")
            })
            .collect(),
        Err(error) => {
            // A crate without the directory still builds: the corpus has no
            // overrides in that checkout, but the mechanism stays available.
            println!(
                "cargo:warning=cannot read {}: {error}",
                overrides_dir.display()
            );
            Vec::new()
        }
    };
    files.sort();

    let mut generated = String::new();
    generated.push_str(
        "// @generated by crates/modv-renderers/build.rs — do not edit.\n\
         // Every `src/isf/overrides/*.wgsl` file, embedded with `include_str!`.\n\
         pub const EMBEDDED_OVERRIDES: &[(&str, &str)] = &[\n",
    );
    for path in &files {
        let stem = path
            .file_stem()
            .and_then(|stem| stem.to_str())
            .expect("override file names are valid UTF-8");
        let absolute = absolute_path(path);
        writeln!(
            generated,
            "    ({stem:?}, include_str!({:?})),",
            absolute.display().to_string()
        )
        .expect("writing to a String cannot fail");
    }
    generated.push_str("];\n");

    let destination = Path::new(&std::env::var_os("OUT_DIR").expect("OUT_DIR is set by cargo"))
        .join("isf_overrides.rs");
    std::fs::write(&destination, generated).expect("write the generated override table");
}

/// `include_str!` resolves relative paths against the *generated* file
/// (`$OUT_DIR`), so emit absolute paths.
fn absolute_path(path: &Path) -> PathBuf {
    if path.is_absolute() {
        return path.to_path_buf();
    }
    std::env::current_dir()
        .map(|cwd| cwd.join(path))
        .unwrap_or_else(|_| path.to_path_buf())
}
